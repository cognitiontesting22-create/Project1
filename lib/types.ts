export type Group = {
  id: number;
  name: string;
  description: string;
  emoji: string;
  currency: string;
  created_at: string;
};

export type Member = {
  id: number;
  group_id: number;
  name: string;
  email: string | null;
  created_at: string;
};

export type SplitType = 'equal' | 'exact' | 'percent' | 'shares';

export const SPLIT_TYPES: SplitType[] = ['equal', 'exact', 'percent', 'shares'];

export function isSplitType(value: string): value is SplitType {
  return (SPLIT_TYPES as string[]).includes(value);
}

/** Past tense, for "split …" in the expense list. */
export const SPLIT_LABELS: Record<SplitType, string> = {
  equal: 'equally',
  exact: 'by exact amounts',
  percent: 'by percentage',
  shares: 'by shares',
};

/** Columns every money-carrying row shares once currencies are in play. */
export type Converted = {
  /** Always in the group's currency — this is what balances are built from. */
  amount_cents: number;
  /** What the user typed, in the currency they typed it in. */
  original_amount_cents: number;
  original_currency: string;
  /** The original→group rate this row was booked at, scaled by 1e8. */
  rate_e8: number;
};

export type Expense = Converted & {
  id: number;
  group_id: number;
  description: string;
  paid_by: number;
  category: string;
  split_type: SplitType;
  spent_at: string;
  created_at: string;
  /** Set when this row was materialised from a recurring template. */
  recurring_id: number | null;
  /** The schedule period it covers, e.g. "2026-02". */
  period: string | null;
};

export type ExchangeRate = {
  currency: string;
  rate_e8: number;
  updated_at: string;
};

export type Split = {
  member_id: number;
  amount_cents: number;
  /**
   * What the user typed, in hundredths of the split's unit: basis points for
   * `percent`, centishares for `shares`, null when `amount_cents` is itself the
   * input (`equal`, `exact`).
   */
  weight: number | null;
};

/** Whether a row was entered by a person or generated by the app. */
export type RowSource = 'manual' | 'recurring' | 'plan';

export type ExpenseWithSplits = Expense & {
  paid_by_name: string;
  source: RowSource;
  splits: (Split & { name: string })[];
};

export type Settlement = Converted & {
  id: number;
  group_id: number;
  from_member_id: number;
  to_member_id: number;
  note: string;
  settled_at: string;
  created_at: string;
};

export type SettlementWithNames = Settlement & {
  from_name: string;
  to_name: string;
  source: RowSource;
};

/** Net position for a member: positive = owed money, negative = owes money. */
export type Balance = {
  member_id: number;
  name: string;
  paid_cents: number;
  owed_cents: number;
  net_cents: number;
};

/** A single "X pays Y $Z" instruction from the debt simplifier. */
export type Debt = {
  from_member_id: number;
  from_name: string;
  to_member_id: number;
  to_name: string;
  amount_cents: number;
};

export type GroupSummary = Group & {
  member_count: number;
  member_names: string[];
  expense_count: number;
  total_cents: number;
};

